"""AI deep-dive brief — everything known about one home, as pasteable markdown.

The workflow this serves (docs/13 §9): tour a home, import the field kit, then
hand a viable candidate to an AI along with the disclosure packet for a deeper
read than the app itself performs.

The section that earns this file's existence is **"What I could not verify"**.
Anyone can dump what they know; the useful move is handing over the gaps
explicitly, so the reader can rank which unknowns actually move the number
instead of quietly assuming the silence was a clean bill of health.

Pure assembly — every number comes from the existing engines (docs/06). Nothing
here computes valuation.
"""

from sqlalchemy import select
from sqlalchemy.orm import Session

from hb import listing_contact, packs, tour_spec
from hb.config import settings
from hb.db.models import (
    AvmSnapshot,
    BuyerProfile,
    CmaComp,
    CmaRun,
    Contact,
    HazardFlag,
    Listing,
    ListingGroup,
    Property,
    PropertyTour,
    Sale,
)

def _money(n) -> str:
    if n is None:
        return "—"
    return f"${n:,.0f}"


def _pct(n) -> str:
    return "—" if n is None else f"{n * 100:.1f}%"


def _phone(digits: str | None) -> str | None:
    """Ten digits -> 650-555-0123; anything else passes through untouched."""
    if not digits:
        return None
    if len(digits) == 10 and digits.isdigit():
        return f"{digits[:3]}-{digits[3:6]}-{digits[6:]}"
    return digits


def _listing_side_lines(session: Session, listing: Listing) -> list[str]:
    """Who is on the other side of the table — the agent off the MLS record and
    any contact saved on the listing. Stated as fact so the reader knows whose
    words the disclosure packet arrives wrapped in."""
    lines: list[str] = []
    side = listing_contact.from_raw(listing.raw)
    if side:
        who = side["agent"] or side["office"]
        parts = [who["name"]]
        if side["agent"] and side["office"]:
            parts.append(side["office"]["name"])
        if who["phones"]:
            parts.append(_phone(who["phones"][0]["number"]))
        if who["email"]:
            parts.append(who["email"])
        lines.append("- **Listing side** (represents the seller, not me): "
                     + " · ".join(p for p in parts if p))
    for c in session.execute(
        select(Contact).where(Contact.listing_id == listing.id).order_by(Contact.kind)
    ).scalars():
        bits = [c.name, c.company, c.phone, c.email]
        lines.append(f"- **Contact ({c.kind.replace('_', ' ')})**: "
                     + " · ".join(b for b in bits if b))
    return lines


def build_brief(session: Session, listing_id: str) -> str:
    from hb.api.listings import _sqft_mismatch, _summary, attach_posture
    from hb.api.tours import facts_for
    from hb.engine import affordability, exposure, offer, posture, valuation
    from hb.schools_match import schools_for_property

    listing = session.get(Listing, listing_id)
    if listing is None:
        raise ValueError(f"listing not found: {listing_id}")
    prop = session.get(Property, listing.property_id)
    group = (session.get(ListingGroup, listing.listing_group_id)
             if listing.listing_group_id else None)

    cache: dict = {}
    summary = _summary(session, listing, prop, group, False)
    summary.predicted_sale = valuation.predicted_sale(session, listing, prop, cache)
    post = attach_posture(session, summary, listing, prop, cache)
    predicted = summary.predicted_sale or {}
    cma_estimate = cache.get(("cma_estimate", prop.id))

    facts = facts_for(session, prop)
    tour = session.execute(
        select(PropertyTour).where(PropertyTour.property_id == prop.id)
        .order_by(PropertyTour.toured_on.desc())
    ).scalars().first()
    pack = packs.current()
    items = tour_spec.items_for(facts, pack)
    rollup = tour_spec.evaluate(tour.checklist if tour else {}, items=items, pack=pack)

    out: list[str] = []
    w = out.append

    # 1. Subject
    w(f"# Deep-dive brief — {summary.address}")
    w("")
    w("_Generated by the home-buying app. Every figure below is from public data or "
      "my own walk-through; nothing here is from an agent._")
    w("")
    w("## 1. Subject")
    w("")
    w(f"- **Address**: {summary.address}, {prop.city or '?'} {prop.zip}")
    w(f"- **Facts**: {prop.beds or '?'} bd / {prop.baths or '?'} ba / "
      f"{prop.sqft or '?'} sqft on {prop.lot_sqft or '?'} sqft lot, built "
      f"{prop.year_built or '?'}")
    if prop.assessor_sqft:
        flag = " — **>15% mismatch, ask what was added and whether it was permitted**" \
            if _sqft_mismatch(prop) else ""
        w(f"- **Assessor sqft**: {prop.assessor_sqft} vs {prop.sqft} listed{flag}")
    w(f"- **Property type**: {prop.property_type}")
    for line in _listing_side_lines(session, listing):
        w(line)

    # 2. Market position
    w("")
    w("## 2. Market position")
    w("")
    w(f"- **List price**: {_money(listing.list_price)}"
      + (f" (originally {_money(listing.original_list_price)})"
         if listing.original_list_price and
         listing.original_list_price != listing.list_price else ""))
    if listing.list_price and prop.sqft:
        w(f"- **$/sqft asked**: {_money(round(listing.list_price / prop.sqft))}")
    w(f"- **Status**: {listing.status}, listed {listing.list_date or '?'}")
    cuts = exposure.price_cut_count(session, listing.id)
    w(f"- **Price cuts observed**: {cuts}")
    if group:
        w(f"- **Cumulative DOM**: {group.cumulative_dom} across {group.episode_count} "
          f"listing episode(s) — public DOM resets on relist, this does not")
    if listing.offer_due_at:
        w(f"- **Offer date**: {listing.offer_due_at}")
    if post:
        if post.p_below_list is not None:
            w(f"- **Pricing posture**: **{post.posture}** — about "
              f"{int(post.p_below_list * 10 + 0.5)} in 10 homes with this exposure history "
              f"sell below asking (p={post.p_below_list:.2f}; typical sale "
              f"{post.typical_sold_to_list:.1%} of ask)")
        else:
            w(f"- **Pricing posture**: **{post.posture}** — no exposure data to judge the ask")
        for sig in post.signals or []:
            w(f"  - {sig.get('points'):+} {sig.get('label')} — {sig.get('detail')}")
        if post.value_gap_pct is not None:
            w(f"  - List sits {post.value_gap_pct:+.1%} vs the unadjusted model value — "
              f"informational: list-vs-value does not predict whether a home clears asking "
              f"once exposure is known")
        if post.withdrawal_share:
            w(f"  - Past {posture.WITHDRAWAL_RATIO:.0f}× the area median, about "
              f"{post.withdrawal_share:.0%} of such listings are withdrawn rather than sold")
        if post.rejection_weight:
            w(f"  - Market-rejection weight {post.rejection_weight:.2f}: exposure past the "
              f"area median pulled the served value down from "
              f"{_money(post.unadjusted_point)}")
    if predicted:
        w(f"- **Predicted sale**: {_money(predicted.get('low'))} – "
          f"{_money(predicted.get('high'))}, point {_money(predicted.get('point'))} "
          f"(basis: {predicted.get('basis')})")

    # 3. Valuation
    w("")
    w("## 3. Valuation")
    w("")
    run = session.execute(
        select(CmaRun).where(CmaRun.property_id == prop.id)
        .order_by(CmaRun.created_at.desc())
    ).scalars().first()
    if run:
        w(f"**Own CMA**: {_money(run.estimate)} (range {_money(run.low)} – "
          f"{_money(run.high)}, confidence {run.confidence})")
        w("")
        comps = session.execute(
            select(CmaComp).where(CmaComp.cma_run_id == run.id, CmaComp.included.is_(True))
        ).scalars().all()
        if comps:
            w("| Comp | Sold | Sale price | Adjustments | Adjusted | Similarity |")
            w("|---|---|---|---|---|---|")
            for comp in comps:
                sale = session.get(Sale, comp.sale_id)
                comp_prop = session.get(Property, sale.property_id) if sale else None
                addr = comp_prop.address_norm if comp_prop else comp.sale_id
                sim = (f"{comp.similarity_score:.2f}"
                       if comp.similarity_score is not None else "—")
                items = comp.adjustments or {}
                overridden = set((items.get("_overrides") or {}).keys())
                adj = ", ".join(f"{k} {v:+,.0f}" + ("*" if k in overridden else "")
                                for k, v in items.items()
                                if not k.startswith("_") and v) or "none"
                w(f"| {addr} | {sale.sale_date if sale else '?'} | "
                  f"{_money(sale.sale_price if sale else None)} | {adj} | "
                  f"{_money(comp.adjusted_price)} | {sim} |")
            w("")
            w("_Adjustments are market-derived per docs/06: per-ZIP time adjustment to "
              "today, marginal (not average) $/sqft for size, paired-sale style feature "
              "adjustments. A trailing * marks a line item overridden by hand in the "
              "workbench._")
    else:
        w("**Own CMA**: not yet run for this property.")

    avms = session.execute(
        select(AvmSnapshot).where(AvmSnapshot.property_id == prop.id)
        .order_by(AvmSnapshot.as_of.desc())
    ).scalars().all()
    latest: dict[str, AvmSnapshot] = {}
    for a in avms:
        latest.setdefault(a.source, a)
    if latest:
        w("")
        w("**Third-party AVMs** (an on-market Zestimate anchors to list price — treat "
          "accordingly):")
        for a in latest.values():
            w(f"- {a.source}: {_money(a.value)} as of {a.as_of}")
        values = [a.value for a in latest.values() if a.value]
        if cma_estimate:
            values.append(cma_estimate)
        if len(values) > 1:
            spread = (max(values) - min(values)) / min(values)
            w(f"- Spread across sources: {_pct(spread)} — wider spread means more "
              f"genuine uncertainty, not a better average")

    # 4. Neighborhood
    w("")
    w("## 4. Neighborhood")
    w("")
    schools = schools_for_property(session, prop.lat, prop.lon, prop.zip)
    if schools:
        for s in schools:
            rating = s.get("rating")
            w(f"- **{s.get('level', '?').title()}**: {s.get('name')} — rating "
              f"{rating if rating is not None else '—'}/10, {s.get('distance_mi')} mi "
              f"(match: {s.get('assignment')})")
        w("  _Assignment is by school-district boundary polygon, not nearest school._")
    else:
        w("- No school assignment on file — run `hb pipeline schools`.")
    hazards = session.execute(
        select(HazardFlag).where(HazardFlag.property_id == prop.id)
    ).scalars().all()
    if hazards:
        for h in hazards:
            w(f"- **Hazard**: {h.hazard} = {h.zone_value}")
    else:
        w(f"- No hazard flags on file ({' / '.join(h.label for h in pack.hazards)}).")

    # 5. Money
    w("")
    w("## 5. Money")
    w("")
    profile = session.get(BuyerProfile, "default")
    if profile:
        scenarios = [("list price", listing.list_price),
                     ("CMA estimate", cma_estimate),
                     ("predicted p50", predicted.get("point"))]
        for label, price in scenarios:
            if not price:
                continue
            res = affordability.calc(
                session, price=int(price), city=prop.city,
                down_payment=profile.down_payment or 0,
                rate=profile.rate_assumption,
                insurance_monthly=profile.insurance_monthly_est or 250,
                include_earthquake=bool(profile.include_earthquake_ins),
                cash_available=profile.cash_available or 0,
            )
            warn = "" if res.reserves_ok else "  ⚠️ **reserves below 6 months PITI**"
            w(f"- At **{label}** {_money(price)}: PITI {_money(res.piti)}/mo, "
              f"cash needed {_money(res.cash_needed)}, reserves after "
              f"{_money(res.reserves_after)}{warn}")
        w(f"- _{pack.content.brief_tax_note}_")
        sol = offer.solve(session, listing, prop, profile)
        w(f"- **Offer solver**: recommendation **{(sol.recommendation or '?').upper()}** "
          f"({sol.confidence} confidence); suggested opening "
          f"{_money((sol.opening_range or {}).get('low'))} – "
          f"{_money((sol.opening_range or {}).get('high'))}; value-justified ceiling "
          f"{_money(sol.ceiling)}; cash max {_money(sol.max_defensible_bid)}")
        w(f"  - {sol.verdict}")
    else:
        w("- No buyer profile saved — fill it in on /affordability.")

    # 6-7. The tour
    w("")
    w("## 6. What I observed on the walk-through")
    w("")
    if tour is None:
        w("**No tour recorded.** Everything above is desk research; nothing below the "
          "curb has been verified.")
    else:
        w(f"Toured **{tour.toured_on}** ({tour.kind.replace('_', ' ')})"
          + (f", gut score **{tour.gut_score}/5**" if tour.gut_score else "")
          + (f", verdict **{tour.verdict}**" if tour.verdict else ""))
        w("")
        by_section = {s.key: (s.title, []) for s in pack.tour.sections}
        for item in items:
            value = (tour.checklist or {}).get(item.key)
            if value in (None, "", False):
                continue
            section = next((s.key for s in pack.tour.sections
                            if item.key in {i.key for i in s.items}), "")
            if section in by_section:
                by_section[section][1].append(f"- {item.label}: **{value}**")
        for title, lines in by_section.values():
            if lines:
                w(f"**{title}**")
                w("")
                out.extend(lines)
                w("")
        photos = [k[len("photo:"):] for k, v in (tour.checklist or {}).items()
                  if k.startswith("photo:") and v]
        if photos:
            by_key = tour_spec.items_by_key(pack)
            labels = [by_key[k].label for k in photos if k in by_key]
            w(f"**Photos I took**: {', '.join(labels)} — attached to this conversation.")
            w("")
        answers = tour.agent_answers or {}
        if answers:
            w("**What the listing agent said**")
            w("")
            for idx, answer in sorted(answers.items(), key=lambda kv: int(kv[0])):
                question = pack.tour.agent_questions[int(idx)]
                w(f"- _{question}_ → {answer}")
            w("")
        if tour.notes:
            w("**My notes**")
            w("")
            w(tour.notes)
            w("")

    w("## 7. Deferred maintenance observed")
    w("")
    if not rollup["flags"]:
        w("Nothing flagged — either the home is clean or the checklist is thin. "
          "Check section 8 before assuming the former.")
    else:
        w("| Flagged | Observed | Estimated cost |")
        w("|---|---|---|")
        for flag in rollup["flags"]:
            band = pack.tour.cost_bands.get(flag["cost"])
            cost = (f"{band.label}: {_money(band.low)} – {_money(band.high)}"
                    if band else "not priced")
            w(f"| {flag['label']} | {flag['value']} | {cost} |")
        low = tour.repair_low if tour and tour.repair_low is not None else rollup["costs"]["low"]
        high = tour.repair_high if tour and tour.repair_high is not None else rollup["costs"]["high"]
        w("")
        w(f"**Total deferred maintenance: {_money(low)} – {_money(high)}** "
          f"({pack.tour.cost_bands.year} {pack.tour.cost_bands.label}, deduped by trade "
          f"— wide on purpose)")
        if cma_estimate:
            w("")
            w(f"**Condition-adjusted value: {_money(cma_estimate - high)} – "
              f"{_money(cma_estimate - low)}** against a CMA estimate of "
              f"{_money(cma_estimate)}.")

    # 8. The gaps
    w("")
    w("## 8. What I could NOT verify")
    w("")
    w("Treat these as unknown, not as absent problems. Tell me which of them would "
      "move the number most, and I will go back and check.")
    w("")
    if tour is None:
        w("- Everything on the tour checklist — the home has not been walked.")
    else:
        unanswered = rollup["unanswered"]
        if unanswered:
            for gap in unanswered:
                w(f"- {gap['label']}")
        else:
            w("- Nothing on the checklist was left blank.")
        asked = set((tour.agent_answers or {}).keys())
        unasked = [q for i, q in enumerate(pack.tour.agent_questions)
                   if str(i) not in asked]
        if unasked:
            w("")
            w("**Questions I did not get answered:**")
            w("")
            for q in unasked:
                w(f"- {q}")
    if not run:
        w("- No CMA has been run for this property yet.")
    if not latest:
        w("- No third-party AVM on file to cross-check my own estimate.")

    # 9-10. Handoff
    w("")
    w("## 9. What I am attaching")
    w("")
    for doc in pack.content.disclosure_packet:
        w(f"- {doc}")
    w("- my tour photos (electrical panel with the door open, water heater and furnace "
      "data plates, crawlspace, roofline, drainage, under-sink plumbing, any crack)")
    w("")
    w("## 10. What I want from you")
    w("")
    w(f"1. Price the defects I flagged at current {settings.geo.name} rates, and tell me "
      "where my cost bands are wrong.")
    w("2. Separate genuine deal-breakers from ordinary negotiables. I am a first-time "
      "buyer and I do not yet know which is which.")
    w("3. Read the disclosure packet against what I observed. Where do they disagree, "
      "and what does the packet imply the seller already knows?")
    w("4. Restate the value net of deferred maintenance, and say whether you would bid "
      "at all.")
    w("5. Recommend offer terms — price, contingencies, appraisal-gap coverage, "
      "escalation cap, rent-back — given the posture and competition signals above.")
    w("6. Name the five questions still worth answering before the offer date, ranked "
      "by how much they move the price.")
    w("")

    return "\n".join(out)
